ALTER TABLE bookings ADD COLUMN invitation_hash VARCHAR(64);
CREATE UNIQUE INDEX bookings_invitation_hash_unique ON bookings(invitation_hash) WHERE invitation_hash IS NOT NULL;

CREATE TABLE participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(30) NOT NULL CHECK (status IN ('REQUESTED', 'PENDING_PAYMENT', 'REJECTED', 'CONFIRMED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT participations_one_per_user UNIQUE (booking_id, user_id)
);
CREATE INDEX participations_user_created_idx ON participations(user_id, created_at);
CREATE INDEX participations_match_status_idx ON participations(booking_id, status);
