-- PostgreSQL exclusion constraint also protects overlapping slots after operating-hour changes.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id BIGINT NOT NULL REFERENCES courts(id),
    creator_id BIGINT NOT NULL REFERENCES users(id),
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    sport VARCHAR(20) NOT NULL,
    visibility VARCHAR(20) NOT NULL CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'CANCELLED')),
    minimum_participants INTEGER NOT NULL CHECK (minimum_participants > 0),
    CONSTRAINT bookings_one_hour CHECK (ends_at = starts_at + INTERVAL '1 hour'),
    CONSTRAINT bookings_no_overlap EXCLUDE USING gist (
        court_id WITH =,
        tsrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status <> 'CANCELLED')
);
CREATE INDEX bookings_creator_created_at_idx ON bookings(creator_id, created_at);
