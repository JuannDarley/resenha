-- Existing courts stay unconfigured until the owner chooses a minimum.
ALTER TABLE courts ADD COLUMN minimum_participants INTEGER;
ALTER TABLE courts ADD CONSTRAINT courts_minimum_participants_positive
    CHECK (minimum_participants IS NULL OR minimum_participants > 0);

CREATE TABLE court_slot_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id BIGINT NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
    starts_at TIMESTAMP NOT NULL,
    CONSTRAINT court_slot_blocks_unique UNIQUE (court_id, starts_at)
);
